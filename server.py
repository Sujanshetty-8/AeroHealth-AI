@app.post(
    "/chat",
    response_model=ChatResponse
)

async def chat_endpoint(
    req: ChatRequest
):

    # -----------------------------
    # Validate request
    # -----------------------------

    if not req.session_id:

        raise HTTPException(

            status_code=400,

            detail="session_id is required"

        )


    if not req.user_id:

        raise HTTPException(

            status_code=400,

            detail="user_id is required"

        )


    # -----------------------------
    # Create conversation manager
    # -----------------------------

    if req.session_id not in sessions:

        print(
            "\nCreating new conversation..."
        )

        print(
            "User ID:",
            req.user_id
        )


        sessions[
            req.session_id
        ] = ConversationManager(

            user_id=req.user_id

        )


    manager = sessions[
        req.session_id
    ]


    # -----------------------------
    # Process message
    # -----------------------------

    try:

        reply = manager.process(
            req.message
        )


        return ChatResponse(

            reply=reply,

            stage=manager.state.get(
                "stage",
                ""
            ),

            booking_complete=
                manager.state.get(
                    "booking_complete",
                    False
                )

        )


    except Exception as e:

        print(
            f"Error processing message: {e}"
        )


        raise HTTPException(

            status_code=500,

            detail=str(e)

        )


