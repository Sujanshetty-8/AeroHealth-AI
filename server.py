def normalize_indian_phone_number(value: str) -> str:

    """Normalize a 10-digit Indian mobile number to E.164 (+91...)."""

    raw = (value or "").strip()
    digits = re.sub(r"\D", "", raw)

    if len(digits) == 10:
        number = "+91" + digits
    elif len(digits) == 11 and digits.startswith("0"):
        number = "+91" + digits[1:]
    elif len(digits) == 12 and digits.startswith("91"):
        number = "+" + digits
    else:
        raise ValueError("Enter a valid 10-digit Indian mobile number, optionally with +91.")

    # Basic Indian mobile validation; the carrier still determines reachability.
    if not re.fullmatch(r"\+91[6-9]\d{9}", number):
        raise ValueError("Enter a valid Indian mobile number beginning with 6, 7, 8, or 9.")

    return number


def _get_vapi_tool_token(payload: dict) -> str | None:

    # Function-tool Static Body Fields are merged into the root request body.
    # The alternate paths make local testing and tool-version differences easier to diagnose.
    message = payload.get("message") or {}
    call = message.get("call") or {}
    metadata = call.get("metadata") or {}

    return (
        payload.get("aerohealthCallbackToken")
        or payload.get("aerohealth_callback_token")
        or message.get("aerohealthCallbackToken")
        or message.get("aerohealth_callback_token")
        or metadata.get("aerohealthCallbackToken")
        or metadata.get("aerohealth_callback_token")
    )


