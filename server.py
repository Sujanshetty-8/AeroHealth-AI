@app.post("/request-callback")
async def request_callback(
    req: CallbackRequest,
    authorization: str | None = Header(default=None),
):

    if not req.consent:
        raise HTTPException(
            status_code=400,
            detail="Consent is required before requesting an automated call.",
        )

    if not authorization or not authorization.lower().startswith("bearer "):
        raise HTTPException(
            status_code=401,
            detail="Please sign in again before requesting a call.",
        )

    access_token = authorization.split(" ", 1)[1].strip()
    if not access_token:
        raise HTTPException(status_code=401, detail="Missing authentication token.")

    # Verify the Supabase access token instead of trusting a user_id supplied by React.
    try:
        auth_response = await asyncio.to_thread(
            supabase.auth.get_user, access_token
        )
        authenticated_user = getattr(auth_response, "user", None)
        user_id = getattr(authenticated_user, "id", None)
        if not user_id:
            raise ValueError("Supabase did not return an authenticated user.")
    except Exception:
        raise HTTPException(
            status_code=401,
            detail="Your login session could not be verified. Please sign in again.",
        )

    try:
        phone_number = normalize_indian_phone_number(req.phone_number)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))

    vapi_private_key = os.getenv("VAPI_PRIVATE_KEY")
    vapi_assistant_id = os.getenv("VAPI_ASSISTANT_ID")
    vapi_phone_number_id = os.getenv("VAPI_PHONE_NUMBER_ID")

    if not all([vapi_private_key, vapi_assistant_id, vapi_phone_number_id]):
        raise HTTPException(
            status_code=503,
            detail="Phone callbacks are not configured on the server yet.",
        )

    _cleanup_phone_sessions()
    callback_token = secrets.token_urlsafe(32)

    # Reuse the existing booking manager and scheduler. Associate the number
    # with this authenticated user's session so the appointment keeps user_id.
    manager = ConversationManager(user_id=str(user_id))
    manager.state["patient"]["phone"] = phone_number

    phone_sessions[callback_token] = {
        "manager": manager,
        "user_id": str(user_id),
        "phone_number": phone_number,
        "created_at": time.time(),
    }

    call_payload = {
        "assistantId": vapi_assistant_id,
        "phoneNumberId": vapi_phone_number_id,
        "customer": {"number": phone_number},
        "assistantOverrides": {
            "variableValues": {
                # Vapi Function tool passes this server-created value back using
                # its Static Body Fields template; never ask the model to invent it.
                "aerohealthCallbackToken": callback_token,
            }
        },
        "metadata": {
            "source": "aerohealth_callback",
            "aerohealthCallbackToken": callback_token,
        },
    }

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            response = await client.post(
                "https://api.vapi.ai/call",
                headers={
                    "Authorization": f"Bearer {vapi_private_key}",
                    "Content-Type": "application/json",
                },
                json=call_payload,
            )

        if response.status_code >= 400:
            phone_sessions.pop(callback_token, None)
            print("Vapi call creation failed with HTTP", response.status_code)
            raise HTTPException(
                status_code=502,
                detail=(
                    "Vapi could not start the call. Check your assistant ID, "
                    "phone number ID, account balance, and outbound calling permissions."
                ),
            )

        call_data = response.json()
        return {
            "status": "queued",
            "message": "Your callback request was accepted. AeroHealth AI will call you shortly.",
            "call_id": call_data.get("id"),
        }

    except HTTPException:
        raise
    except Exception as exc:
        phone_sessions.pop(callback_token, None)
        print("Error requesting Vapi call:", type(exc).__name__)
        raise HTTPException(
            status_code=502,
            detail="Could not contact Vapi. Please try again shortly.",
        )


