@app.post(
    "/transcribe"
)

async def transcribe_audio(
    audio: UploadFile = File(...)
):

    # -----------------------------
    # Save temporary audio file
    # -----------------------------

    temp_file_path = (
        f"temp_{audio.filename}"
    )


    with open(
        temp_file_path,
        "wb"
    ) as buffer:

        shutil.copyfileobj(
            audio.file,
            buffer
        )


    try:

        # -----------------------------
        # Load multilingual Whisper
        # -----------------------------

        model = get_whisper_model()


        # -----------------------------
        # Transcribe
        # -----------------------------
        #
        # language=None
        # means Whisper automatically
        # detects the spoken language.
        #
        # This allows:
        #
        # English
        # Kannada
        # and other supported languages.
        #
        # -----------------------------

        segments, info = model.transcribe(

            temp_file_path,

            beam_size=5,

            language="kn",

            task="transcribe",

            vad_filter=True,

            condition_on_previous_text=False

        )


        # -----------------------------
        # Combine segments
        # -----------------------------

        text = " ".join(

            [
                segment.text
                for segment in segments
            ]

        ).strip()


        # -----------------------------
        # Detected language
        # -----------------------------

        detected_language = (
            info.language
            if info
            else None
        )


        language_probability = (

            info.language_probability
            if info
            else None

        )


        print(
            "\n========== SPEECH RECOGNITION =========="
        )

        print(
            "Detected language:",
            detected_language
        )

        print(
            "Language probability:",
            language_probability
        )

        print(
            "Transcribed text:",
            text
        )

        print(
            "=========================================\n"
        )


        return {

            "text": text,

            "language": detected_language,

            "language_probability":
                language_probability

        }


    except Exception as e:

        print(
            f"Transcription error: {e}"
        )


        raise HTTPException(

            status_code=500,

            detail=str(e)

        )


    finally:

        # -----------------------------
        # Remove temporary file
        # -----------------------------

        if os.path.exists(
            temp_file_path
        ):

            os.remove(
                temp_file_path
            )


