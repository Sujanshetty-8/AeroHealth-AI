@app.post("/vapi/tools")
async def vapi_tool_webhook(
    payload: dict,
    x_aerohealth_tool_secret: str | None = Header(default=None),
):

    expected_secret = os.getenv("VAPI_TOOL_SECRET", "")
    if not expected_secret:
        raise HTTPException(status_code=503, detail="Vapi tool authentication is not configured.")

    if not x_aerohealth_tool_secret or not hmac.compare_digest(
        x_aerohealth_tool_secret, expected_secret
    ):
        raise HTTPException(status_code=401, detail="Unauthorized tool request.")

    message = payload.get("message") or {}
    tool_calls = message.get("toolCallList") or []
    callback_token = _get_vapi_tool_token(payload)

    if not tool_calls:
        # Vapi can deliver non-tool server events to a configured URL; acknowledge them.
        return {"received": True}

    record = phone_sessions.get(callback_token) if callback_token else None
    if not record:
        return {
            "results": [
                {
                    "toolCallId": item.get("id", "unknown"),
                    "error": "This callback session has expired or is invalid. Please request a new call from AeroHealth AI.",
                }
                for item in tool_calls
            ]
        }

    results = []
    manager = record["manager"]

    for item in tool_calls:
        tool_call_id = item.get("id") or item.get("toolCall", {}).get("id") or "unknown"
        tool_name = item.get("name") or item.get("function", {}).get("name") or ""
        arguments = item.get("parameters") or item.get("arguments") or item.get("function", {}).get("arguments") or {}
        if isinstance(arguments, str):
            try:
                import json
                arguments = json.loads(arguments)
            except Exception:
                arguments = {}

        if tool_name not in {"aerohealth_booking", "continue_appointment_booking", "function_tool"}:
            results.append({"toolCallId": tool_call_id, "error": "Unknown AeroHealth tool. Please continue the booking conversation without claiming a booking was completed."})
            continue

        patient_message = str(arguments.get("message", "")).strip()
        if not patient_message:
            results.append({"toolCallId": tool_call_id, "error": "The patient's latest response was empty. Ask the patient to repeat it."})
            continue

        if manager.is_cancellation_request(patient_message):
            results.append({"toolCallId": tool_call_id, "result": "This phone assistant currently handles new appointment bookings only. It cannot cancel appointments. Ask whether the patient would like to continue with a new booking."})
            continue

        try:
            reply = await asyncio.to_thread(manager.process, patient_message)
            # Vapi expects a single-line string in result.
            reply = " ".join(str(reply).split())
            results.append({"toolCallId": tool_call_id, "result": reply})
        except Exception as exc:
            print("Vapi booking tool error:", type(exc).__name__)
            results.append({"toolCallId": tool_call_id, "error": "AeroHealth could not process that booking response. Please ask the patient to repeat or try again."})

    return {"results": results}


