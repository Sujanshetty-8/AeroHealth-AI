sessions = {}

# Phone sessions are keyed by an opaque token generated by this backend.
# Vapi receives the token as a server-side template value; the LLM cannot choose it.
phone_sessions = {}
PHONE_SESSION_TTL_SECONDS = 2 * 60 * 60


def _cleanup_phone_sessions():

    cutoff = time.time() - PHONE_SESSION_TTL_SECONDS

    expired = [
        token
        for token, record in phone_sessions.items()
        if record.get("created_at", 0) < cutoff
    ]

    for token in expired:
        phone_sessions.pop(token, None)


